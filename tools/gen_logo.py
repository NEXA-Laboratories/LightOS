#!/usr/bin/env python3
"""Rasterise tools/lightos.svg into half-block text art and emit kernel/src/logo.rs.
Needs Pillow (pip install pillow). Usage: python3 tools/gen_logo.py [width_in_columns]"""
import os, re, sys
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
COLS = int(sys.argv[1]) if len(sys.argv) > 1 else 76
SS = 6  # supersampling

svg = open(os.path.join(HERE, "lightos.svg"), encoding="utf-8").read()
vb = [float(x) for x in re.search(r'viewBox="([^"]+)"', svg).group(1).split()]
paths = re.findall(r'<path d="([^"]+)"[^>]*fill="([^"]+)"', svg)

def flatten(d):
    toks = re.findall(r"[MLHVCZ]|-?\d*\.?\d+(?:e-?\d+)?", d)
    polys, cur, i, x, y, cmd = [], [], 0, 0.0, 0.0, None
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t; i += 1
            if cmd == "Z":
                if cur: polys.append(cur); cur = []
                continue
        n = lambda k: float(toks[i + k])
        if cmd == "M":
            if cur: polys.append(cur)
            x, y = n(0), n(1); cur = [(x, y)]; i += 2; cmd = "L"
        elif cmd == "L":
            x, y = n(0), n(1); cur.append((x, y)); i += 2
        elif cmd == "H":
            x = n(0); cur.append((x, y)); i += 1
        elif cmd == "V":
            y = n(0); cur.append((x, y)); i += 1
        elif cmd == "C":
            x1, y1, x2, y2, x3, y3 = (n(k) for k in range(6)); i += 6
            for s in range(1, 13):
                u = s / 12
                a, b, c, e = (1-u)**3, 3*u*(1-u)**2, 3*u*u*(1-u), u**3
                cur.append((a*x + b*x1 + c*x2 + e*x3, a*y + b*y1 + c*y2 + e*y3))
            x, y = x3, y3
        else:
            raise SystemExit(f"unsupported path command {cmd}")
    if cur: polys.append(cur)
    return polys

PXW = COLS
PXH = round(COLS * vb[3] / vb[2])
PXH += PXH % 2
W, H = PXW * SS, PXH * SS
sx, sy = W / vb[2], H / vb[3]
canvas = Image.new("L", (W, H), 0)
for d, fill in paths:
    mask = Image.new("1", (W, H), 0)
    for poly in flatten(d):               # even-odd via XOR of sub-polygons
        layer = Image.new("1", (W, H), 0)
        ImageDraw.Draw(layer).polygon([((px - vb[0]) * sx, (py - vb[1]) * sy) for px, py in poly], fill=1)
        m_a, l_a = mask.load(), layer.load()
        for yy in range(H):
            for xx in range(W):
                if l_a[xx, yy]:
                    m_a[xx, yy] = 0 if m_a[xx, yy] else 1
    value = 0 if fill.lower() == "#171717" else 255
    canvas.paste(value, mask=mask)

small = canvas.resize((PXW, PXH), Image.BOX)
px = small.load()
rows = []
for r in range(0, PXH, 2):
    line = ""
    for c in range(PXW):
        top, bot = px[c, r] > 127, px[c, r + 1] > 127
        line += "█" if top and bot else "▀" if top else "▄" if bot else " "
    rows.append(line.rstrip().ljust(PXW))
for l in rows: print(l)

out = os.path.join(HERE, "..", "kernel", "src", "logo.rs")
with open(out, "w", encoding="utf-8") as f:
    f.write("//! Generated by tools/gen_logo.py from tools/lightos.svg - do not edit by hand.\n")
    f.write(f"pub const LOGO_W: usize = {PXW};\n")
    f.write(f"pub const LOGO_H: usize = {len(rows)};\n")
    f.write("pub const LOGO: [&str; LOGO_H] = [\n")
    for l in rows: f.write(f'    "{l}",\n')
    f.write("];\n")
print(f"\nwrote {out} ({PXW}x{len(rows)} cells)")
