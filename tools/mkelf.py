#!/usr/bin/env python3
"""Hand-assemble a tiny static ELF64 test app for LightOS and publish it as the `hello-elf` package.

The app is position-dependent: it is linked at 0x0000_0100_0000_0000 (the LightOS app region),
prints a line with SYS_WRITE and leaves with SYS_EXIT, using the int 0x80 ABI
(rax = number, rdi/rsi/rdx = args).
Outputs: disk-root/BIN/HELLO.ELF, repo/hello-elf/*, kernel/src/los/hello_elf.rs
"""
import os, struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = 0x0000_0100_0000_0000
HDR = 64 + 56

MSG = b"Hello from a native ELF64 app running on LightOS 0.3.0!\n"

def build():
    code = bytearray()
    code += b"\xB8\x01\x00\x00\x00"                      # mov eax, 1      (SYS_WRITE)
    code += b"\xBF\x01\x00\x00\x00"                      # mov edi, 1      (stdout)
    lea_at = len(code)
    code += b"\x48\x8D\x35\x00\x00\x00\x00"              # lea rsi, [rip+msg]
    code += b"\xBA" + struct.pack("<I", len(MSG))        # mov edx, len
    code += b"\xCD\x80"                                  # int 0x80
    code += b"\xB8\x02\x00\x00\x00"                      # mov eax, 2      (SYS_GETPID)
    code += b"\xCD\x80"                                  # int 0x80  (result unused)
    code += b"\xB8\x03\x00\x00\x00"                      # mov eax, 3      (SYS_EXIT)
    code += b"\x31\xFF"                                  # xor edi, edi
    code += b"\xCD\x80"                                  # int 0x80
    code += b"\xF4\xEB\xFD"                              # hlt; jmp -3
    msg_off = len(code)
    rel = msg_off - (lea_at + 7)
    code[lea_at + 3:lea_at + 7] = struct.pack("<i", rel)
    code += MSG
    total = HDR + len(code)
    ehdr = b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8)
    ehdr += struct.pack("<HHIQQQIHHHHHH", 2, 0x3E, 1, BASE + HDR, 64, 0, 0, 64, 56, 1, 0, 0, 0)
    phdr = struct.pack("<IIQQQQQQ", 1, 7, 0, BASE, BASE, total, total, 0x1000)
    return ehdr + phdr + bytes(code)

if __name__ == "__main__":
    elf = build()
    os.makedirs(os.path.join(ROOT, "disk-root", "BIN"), exist_ok=True)
    open(os.path.join(ROOT, "disk-root", "BIN", "HELLO.ELF"), "wb").write(elf)
    hexs = elf.hex()
    payload = "# los-app elf64 hex\n" + "\n".join(hexs[i:i + 64] for i in range(0, len(hexs), 64)) + "\n"
    d = os.path.join(ROOT, "repo", "hello-elf")
    os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "payload.txt"), "w", newline="").write(payload)
    open(os.path.join(d, "package.toml"), "w").write(
        '[package]\nname = "hello-elf"\nversion = "0.3.0"\ndescription = "Hello world ELF64 demo app"\n'
        'author = "LightOS Team"\nlicense = "MIT"\nverified = true\n\n[dependencies]\nlos-core = "0.1.0"\n')
    esc = payload.replace("\\", "\\\\").replace("\n", "\\n")
    open(os.path.join(ROOT, "kernel", "src", "los", "hello_elf.rs"), "w").write(
        "//! Generated by tools/mkelf.py - do not edit by hand.\n"
        f'pub const PAYLOAD: &str = "{esc}";\n')
    print(f"wrote {len(elf)}-byte ELF, payload {len(payload)} bytes")
