#!/usr/bin/env python3
"""Hand-assemble the LightOS ring-3 demo apps and publish them.

All apps are static ELF64 binaries linked at APP_BASE (4 TiB, see kernel/src/elf.rs) and use the
int 0x80 ABI (rax = number, rdi/rsi/rdx = args): 1 = write, 2 = getpid, 3 = exit.

  HELLO.ELF  prints a line and exits                      (package hello-elf, also built into the kernel)
  CRASH.ELF  reads kernel memory  -> page fault, killed   (package crash-elf)
  PRIV.ELF   executes HLT         -> #GP, killed          (package priv-elf)
  SPIN.ELF   loops forever        -> stop it with Ctrl+C  (package spin-elf)

Outputs: disk-root/BIN/*.ELF, repo/<package>/*, kernel/src/los/hello_elf.rs
"""
import os, struct

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BASE = 0x0000_0400_0000_0000
HDR = 64 + 56

EXIT = b"\xB8\x03\x00\x00\x00\x31\xFF\xCD\x80\xF4\xEB\xFD"          # mov eax,3; xor edi,edi; int 0x80; hlt; jmp $
GETPID_EXIT = b"\xB8\x02\x00\x00\x00\xCD\x80" + EXIT
CRASH_TAIL = b"\x48\xB8\x00\x00\x20\x00\x00\x00\x00\x00\x48\x8B\x18" + EXIT   # mov rax,0x200000; mov rbx,[rax]
PRIV_TAIL = b"\xF4" + EXIT                                           # hlt in ring 3
SPIN_TAIL = b"\xEB\xFE"                                              # jmp $


def build(msg, tail):
    code = bytearray()
    code += b"\xB8\x01\x00\x00\x00"                      # mov eax, 1      (SYS_WRITE)
    code += b"\xBF\x01\x00\x00\x00"                      # mov edi, 1      (stdout)
    lea_at = len(code)
    code += b"\x48\x8D\x35\x00\x00\x00\x00"              # lea rsi, [rip+msg]
    code += b"\xBA" + struct.pack("<I", len(msg))        # mov edx, len
    code += b"\xCD\x80"                                  # int 0x80
    code += tail
    msg_off = len(code)
    code[lea_at + 3:lea_at + 7] = struct.pack("<i", msg_off - (lea_at + 7))
    code += msg
    total = HDR + len(code)
    ehdr = b"\x7fELF" + bytes([2, 1, 1, 0]) + bytes(8)
    ehdr += struct.pack("<HHIQQQIHHHHHH", 2, 0x3E, 1, BASE + HDR, 64, 0, 0, 64, 56, 1, 0, 0, 0)
    phdr = struct.pack("<IIQQQQQQ", 1, 7, 0, BASE, BASE, total, total, 0x1000)
    return ehdr + phdr + bytes(code)


APPS = [
    # (file, package, description, message, tail)
    ("HELLO", "hello-elf", "Hello world ELF64 demo app (ring 3)", b"Hello from a native ELF64 app running in ring 3 on LightOS 0.5.0!\n", GETPID_EXIT),
    ("CRASH", "crash-elf", "Ring 3 demo: reads kernel memory and is killed", b"crash-elf: reading kernel memory from ring 3 (the kernel must stop this)...\n", CRASH_TAIL),
    ("PRIV", "priv-elf", "Ring 3 demo: runs HLT and is killed", b"priv-elf: executing the privileged HLT instruction in ring 3...\n", PRIV_TAIL),
    ("SPIN", "spin-elf", "Ring 3 demo: loops forever, stop with Ctrl+C", b"spin-elf: looping forever - press Ctrl+C (or Esc) to stop me\n", SPIN_TAIL),
]

if __name__ == "__main__":
    os.makedirs(os.path.join(ROOT, "disk-root", "BIN"), exist_ok=True)
    for fname, pkg, desc, msg, tail in APPS:
        elf = build(msg, tail)
        open(os.path.join(ROOT, "disk-root", "BIN", fname + ".ELF"), "wb").write(elf)
        hexs = elf.hex()
        payload = "# los-app elf64 hex\n" + "\n".join(hexs[i:i + 64] for i in range(0, len(hexs), 64)) + "\n"
        d = os.path.join(ROOT, "repo", pkg)
        os.makedirs(d, exist_ok=True)
        open(os.path.join(d, "payload.txt"), "w", newline="").write(payload)
        open(os.path.join(d, "package.toml"), "w").write(
            f'[package]\nname = "{pkg}"\nversion = "0.5.0"\ndescription = "{desc}"\n'
            'author = "LightOS Team"\nlicense = "MIT"\nverified = true\n\n[dependencies]\nlos-core = "0.1.0"\n')
        if pkg == "hello-elf":
            esc = payload.replace("\\", "\\\\").replace("\n", "\\n")
            open(os.path.join(ROOT, "kernel", "src", "los", "hello_elf.rs"), "w").write(
                "//! Generated by tools/mkelf.py - do not edit by hand.\n"
                f'pub const PAYLOAD: &str = "{esc}";\n')
        print(f"{fname}.ELF: {len(elf)} bytes -> package {pkg} ({len(payload)} bytes payload)")
